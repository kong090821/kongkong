    fun getMomcafeRank1Product(itemTitle: String): String {
        val cleanTitle = itemTitle
            .replace(Regex("\\(.*?\\)"), "")
            .replace(Regex("[0-9]+.*?[개팩벌세트장]"), "")
            .trim()

        val found = weeklyMomcafeRankingDB.entries.firstOrNull { (k, _) ->
            cleanTitle.contains(k) || k.contains(cleanTitle)
        }
        if (found != null) return found.value

        val recs = getTop3Recommendations(itemTitle)
        if (recs.isNotEmpty()) {
            return recs[0].brandAndName.replace(Regex("\\[.*?\\]"), "").trim()
        }
        return "${cleanTitle} 국민 추천템"
    }

    fun getTop3Recommendations(itemTitle: String): List<ProductRecommendation> {
        val cleanTitle = itemTitle
            .replace(Regex("\\(.*?\\)"), "")
            .replace(Regex("[0-9]+.*?[개팩벌세트장]"), "")
            .trim()

        val foundEntry = curatedDB.entries.firstOrNull { (key, _) ->
            cleanTitle.contains(key) || key.contains(cleanTitle)
        }

        val rawList = foundEntry?.value ?: listOf(
            Pair("[국민템] 프리미엄 순면 $cleanTitle 베스트 세트", "• 선배맘 누적 실구매 후기 1위, 저자극 안심 소재 및 만족도 98%"),
            Pair("[가성비] 스마트 에코 $cleanTitle 실속 2종 세트", "• 합리적인 가격과 필수 기능 집중, 부모들의 가성비 극찬 베스트셀러"),
            Pair("[오가닉] 저자극 무형광 친환경 $cleanTitle", "• 유해물질 불검출 안전 인증 통과, 민감한 신생아 및 산모 피부 케어")
        )

        val badges = listOf("🥇 1위", "🥈 2위", "🥉 3위")

        // 1위용 맘카페 언급 1위 제품명 매핑
        val momcafeRank1 = getMomcafeRank1Product(itemTitle)

        return rawList.take(3).mapIndexed { idx, (name, feature) ->
            val encodedQuery = URLEncoder.encode(name, StandardCharsets.UTF_8.toString())
            val tag = when (idx) {
                0 -> "♥맘카페 언급 1위 $momcafeRank1"
                1 -> "🥈 맘카페 만족도 2위"
                else -> "🥉 가성비/실사용 추천"
            }
            ProductRecommendation(
                rank = idx + 1,
                rankBadge = badges.getOrElse(idx) { "${idx + 1}위" },
                brandAndName = name,
                featureSummary = feature,
                url = "https://search.shopping.naver.com/search/all?query=$encodedQuery",
                momcafeTag = tag
            )
        }
    }
